/**
 * Generates supabase/functions/scan-slip/index.ts from src/scanSpec.ts so the
 * server-side scanner always uses the same model, instructions and answer
 * shape as the app. Run: npx tsx scripts/build-scan-function.ts
 */
import fs from 'fs';
import path from 'path';
import { SCAN_MODEL, SCHEMA, SYSTEM_PROMPT } from '../src/scanSpec';

const out = path.join(__dirname, '..', 'supabase', 'functions', 'scan-slip', 'index.ts');

const source = `// GENERATED by scripts/build-scan-function.ts from src/scanSpec.ts — edit those, not this.
//
// Supabase Edge Function "scan-slip": reads a bet slip photo with Claude on the
// project owner's Anthropic key, for signed-in users, up to FREE_CREDIT_USD of
// scanning per account. Each scan's cost is logged in public.scan_usage.
//
// Needs the secret ANTHROPIC_API_KEY (Edge Functions -> Secrets).
import Anthropic from 'npm:@anthropic-ai/sdk@1';
import { createClient } from 'npm:@supabase/supabase-js@2';

/** Free AI scanning per account, in US dollars. */
const FREE_CREDIT_USD = 1.0;

const MODEL = ${JSON.stringify(SCAN_MODEL)};

// $ per million tokens [input, output], used to log each scan's cost.
const PRICES: Record<string, [number, number]> = {
  'claude-opus-5-5': [4, 20],
  'claude-opus-5': [5, 25],
  'claude-opus-4-8': [5, 25],
  'claude-sonnet-5-5': [2, 10],
  'claude-sonnet-5': [2, 10],
  'claude-haiku-5-5': [0.1, 0.5],
};

// Public project values (the same ones shipped in the app).
const SUPABASE_URL = Deno.env.get('SUPABASE_URL') ?? 'https://zielynjbewfhoerigbzm.supabase.co';
const SUPABASE_KEY = 'sb_publishable_0QBt8O7HJwK4IaMurrxX3w_t9ISCUhE';

const SYSTEM_PROMPT = ${JSON.stringify(SYSTEM_PROMPT)};

const SCHEMA = ${JSON.stringify(SCHEMA)};

const CORS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
  'Access-Control-Allow-Methods': 'POST, OPTIONS',
};

const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { ...CORS, 'Content-Type': 'application/json' } });

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: CORS });
  if (req.method !== 'POST') return json({ error: 'method' }, 405);

  // Act as the signed-in user, so row-level security applies to everything below.
  const authHeader = req.headers.get('Authorization') ?? '';
  const db = createClient(SUPABASE_URL, SUPABASE_KEY, {
    global: { headers: { Authorization: authHeader } },
    auth: { persistSession: false },
  });
  const { data: userData } = await db.auth.getUser(authHeader.replace(/^Bearer\\s+/i, ''));
  const user = userData?.user;
  if (!user) return json({ error: 'auth', message: 'Sign in to scan with AI.' }, 401);

  const { data: rows, error: usageErr } = await db.from('scan_usage').select('cost_usd');
  if (usageErr) return json({ error: 'usage', message: usageErr.message }, 500);
  const spent = (rows ?? []).reduce((sum: number, r: { cost_usd: number }) => sum + Number(r.cost_usd), 0);
  if (spent >= FREE_CREDIT_USD) {
    return json({ error: 'limit', spent, limit: FREE_CREDIT_USD }, 402);
  }

  let image = '';
  let today = '';
  try {
    const body = await req.json();
    image = String(body.image ?? '');
    today = String(body.today ?? '').slice(0, 10);
  } catch {
    return json({ error: 'bad_request', message: 'Expected JSON with an image.' }, 400);
  }
  if (!image || image.length > 8_000_000) {
    return json({ error: 'bad_request', message: 'Missing or oversized image.' }, 400);
  }

  const apiKey = Deno.env.get('ANTHROPIC_API_KEY');
  if (!apiKey) return json({ error: 'config', message: 'Scanning is not set up yet.' }, 500);
  const anthropic = new Anthropic({ apiKey });

  let msg;
  try {
    msg = await anthropic.beta.messages.create({
      model: MODEL,
      max_tokens: 16000,
      betas: ['server-side-fallback-2026-07-01'],
      fallbacks: 'default',
      output_config: { effort: 'medium', format: { type: 'json_schema', schema: SCHEMA } },
      system: SYSTEM_PROMPT,
      messages: [
        {
          role: 'user',
          content: [
            { type: 'image', source: { type: 'base64', media_type: 'image/jpeg', data: image } },
            { type: 'text', text: \`Extract the bets from this slip. Today is \${today}.\` },
          ],
        },
      ],
    });
  } catch (e) {
    const status = e instanceof Anthropic.APIError ? e.status ?? 502 : 502;
    const message = e instanceof Error ? e.message : 'Scanning failed';
    return json({ error: 'upstream', status, message }, 502);
  }

  // Log what this scan cost (input incl. cache tokens + output).
  const u = msg.usage ?? {};
  const inputTokens =
    (u.input_tokens ?? 0) + (u.cache_creation_input_tokens ?? 0) + (u.cache_read_input_tokens ?? 0);
  const outputTokens = u.output_tokens ?? 0;
  const [inPrice, outPrice] = PRICES[msg.model] ?? PRICES[MODEL] ?? [5, 25];
  const cost = Math.max(0.00001, (inputTokens * inPrice + outputTokens * outPrice) / 1_000_000);
  await db.from('scan_usage').insert({
    cost_usd: cost,
    input_tokens: inputTokens,
    output_tokens: outputTokens,
    model: msg.model,
  });

  const text = msg.content
    .map((b: { type: string; text?: string }) => (b.type === 'text' ? b.text ?? '' : ''))
    .join('')
    .trim();
  return json({ text, stop_reason: msg.stop_reason, spent: spent + cost, limit: FREE_CREDIT_USD, cost });
});
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, source);
console.log(`wrote ${path.relative(process.cwd(), out)} (${source.length} bytes)`);
